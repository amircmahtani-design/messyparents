  /* A loose hand-drawn circle, the kind you put round something in a notebook. */
  const looseCircle = (style, colour) =>
    `<span class="b-mark" style="${style};color:${inkOf(colour)}"><svg viewBox="0 0 120 110" ` +
    `fill="none" stroke="currentColor" stroke-width="4" stroke-linecap="round">` +
    `<path d="M62 6C31 4 8 26 7 55c-1 30 24 50 55 49 30-1 52-21 52-49C114 26 92 8 62 6"/>` +
    `<path d="M70 9c26 4 42 22 43 45"/></svg></span>`;

  /* A scribbled underline, two passes, like a biro. */
  const scribble = (style, colour) =>
    `<span class="b-mark" style="${style};color:${inkOf(colour)}"><svg viewBox="0 0 240 24" ` +
    `preserveAspectRatio="none" fill="none" stroke="currentColor" stroke-width="5" ` +
    `stroke-linecap="round"><path d="M4 12c46-6 92-8 138-6 34 1 66 4 94 9"/>` +
    `<path d="M14 19c44-5 88-7 132-5 32 1 62 3 88 7"/></svg></span>`;

  /* ---- object props ------------------------------------------------------
     The concept names the objects that belong in the scene. Drawn here as
     inked shapes on their own scraps of paper, at scene scale rather than
     label scale, so a warning slide has a nappy and a bottle in it and a
     helped slide has a lamp — which is a large part of what stops two slides
     looking the same. */
  function prop(name, style, colour, size) {
    const glyph = objectSVG(name);
    if (!glyph) return "";
    return `<span class="b-prop" style="${style};width:${size}px;height:${size}px;` +
      `color:${inkOf(colour || "ink")}">` +
      `<span class="b-prop-bg"></span><span class="b-prop-art">${glyph}</span></span>`;
  }

  const conceptOf = (slide) => (slide && slide.concept) || null;
  const propsOf = (slide, n) => {
    const c = conceptOf(slide);
    return ((c && c.objects) || []).filter(o => OBJECT_PATHS[o]).slice(0, n || 2);
  };


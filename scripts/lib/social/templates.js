    if (items.length) {
      out += `<div class="s-steps" style="left:6%;top:32%;width:60%">` + items.map((it, i) =>
        `<div class="s-step is-tight">${bullet("coral", i)}${labelHTML(it.label, "coral")}</div>`
      ).join("") + `</div>`;
    }
    out += moreHTML(slide.truncatedItems);
    if (slide.band) out += bandHTML(slide.band, "bluePale", "is-foot");

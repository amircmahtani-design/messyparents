/* ============================================================================
   SOCIAL — THE POSTER RENDERER

   One renderer, two consumers:

     • the /social/ dashboard, which scales the markup down for preview
     • scripts/social-render.js, which screenshots it at full size

   Both use THIS file, so what Amir approves on screen is what would be
   exported. A preview drawn by different code from the export is a preview of
   nothing.

   ---------------------------------------------------------------------------
   WHAT THIS FILE REPLACED, AND WHY

   The old renderer drew a cream page with a heading and a rounded card of
   bullet points, once per slide. It was correct, safe, legible and completely
   inert — a website panel enlarged to 1080 pixels. Nobody stops scrolling for
   a page.

   The approved poster references are built out of five things, and so is this:

     1. a painted FIELD — deep blue or warm cream, edge to edge
     2. a torn CREAM SHEET sitting askew on top of it
     3. CHARACTER CUTOUTS, grouped, overlapping and cropped by the bottom edge
     4. a HEADLINE in two or three colours at two or three sizes
     5. hand-drawn MARKS — sparks, arrows, an outlined heart, a brush underline

   ---------------------------------------------------------------------------
   TWO LAYERS, AND THE REASON THEY ARE SEPARATE

     .s-scene   the artwork. Either an image generated by the model from the
                approved references, or — when there is none — a composition
                built here from the approved cutouts and painted shapes.
     .s-type    every readable word, drawn by this file from text that has
                already been through condense.js and safety.js.

   Nothing readable is ever inside .s-scene. That is what lets a medical
   warning be illustrated AND exact: the picture can be generated, the words
   cannot. If a generated base comes back with letters in it, artwork.js
   rejects it and this renderer falls back to the composed scene — which never
   contains a word either.

   ---------------------------------------------------------------------------
   NO FILTER EVER TOUCHES A LETTER

   The torn-paper and brush effects are feTurbulence displacement filters. A
   displacement filter applied to an element containing text displaces the text
   too, and at label sizes that is not a texture, it is a typo: an early build
   of this file rendered "Try a dim, quiet room" as "TAY A DIM, QUIET ROOM"
   because the chip and its words were one filtered element.

   So every painted chip is TWO elements — a filtered background and an
   unfiltered text node on top of it (see chip() below). The rule is absolute:
   if a node has text in it, it has no filter on it. The exported words have to
   be the approved words, character for character.
   ---------------------------------------------------------------------------
   Runs in Node and in the browser: CommonJS when there is a module, a global
   otherwise.
   ========================================================================== */

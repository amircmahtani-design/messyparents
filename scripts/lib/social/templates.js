  /* --------------------------------------------------------------------------
     THE COVER'S GEOMETRY

     The torn sheet, the logo badge and the category pill all have to know how
     tall the headline is, and that is decided by the guide's own question —
     "Why is my baby drinking less milk?" sets one height and "Is it normal to
     feel like I can't handle one more person touching me?" sets another, so a
     fixed sheet is wrong for one of them whichever number you pick. Guessing
     from the line COUNT was the first attempt and it put the badge on Papa's
     head.

     Computed from the same fitSize() the type uses, once, so the dashboard
     preview and the export agree.
     ------------------------------------------------------------------------ */
  const LOGO_W = 196;
  const LOGO_RATIO = 331 / 760;          /* mpc-logo.png */

  function coverGeometry(slide) {
    const H = SIZE.carousel.height;
    const lines = (slide.lines || []).filter(l => l && String(l.t || "").trim());
    const topPct = 5;
    const topPx = H * topPct / 100;

    const headPx = lines.reduce((t, l) =>
      t + fitSize(l.em ? String(l.t).toUpperCase() : l.t, 850, 54, 138), 0) * 1.02;
    const logoPx = slide.logo ? LOGO_W * LOGO_RATIO : 0;
    const gap = slide.logo ? 46 : 0;

    const logoTopPx = topPx + headPx + gap;
    const sheetBottomPx = logoTopPx + logoPx + 44;

    const sheetTop = topPct - 3;
    const sheetBottom = Math.max(sheetTop + 25, Math.min(sheetTop + 52, (sheetBottomPx / H) * 100));
    const r = (n) => Math.round(n * 10) / 10;
    return {
      topPct,
      sheetTop: r(sheetTop),
      sheetH: r(sheetBottom - sheetTop),
      sheetBottom: r(sheetBottom),
      logoTop: r((logoTopPx / H) * 100)
    };
  }


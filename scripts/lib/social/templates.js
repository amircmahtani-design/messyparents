  /* The absolute floor. `min` below is the PREFERRED minimum — the size below
     which a headline stops being a headline — but it is not a hard stop,
     because a line that will not fit at the preferred minimum has to do
     something, and running off the edge of the slide is the worst of the
     available options.

     So a line that cannot fit shrinks past the preference down to 32px, and
     validate.js raises `headline-long` so the operator is told to shorten it
     rather than discovering it in the feed. Overflow is a bug; small type on
     a twenty-word quick answer is a message. */
  const HARD_MIN = 32;

  function fitSize(text, boxW, min, max) {
    const n = Math.max(1, String(text || "").trim().length);
    const ideal = boxW / (n * ADVANCE);
    if (ideal >= min) return Math.round(Math.min(max, ideal));
    return Math.round(Math.max(HARD_MIN, ideal));
  }

